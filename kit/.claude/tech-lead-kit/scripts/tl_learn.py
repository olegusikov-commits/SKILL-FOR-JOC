# ------------------------------------------------------------------ files
def learn_dir(root):
    return os.path.join(memory_dir(root), "learn")


def today():
    return datetime.date.today().isoformat()


def glossary_path(root):
    """Local GLOSSARY.md; after /tl-retro share the published copy is the master and is edited in place."""
    local = os.path.join(learn_dir(root), "GLOSSARY.md")
    if os.path.exists(local):
        return local
    folder = published_dirs(root, load_config(root)).get("glossary")
    published = os.path.join(folder, "GLOSSARY.md") if folder else None
    return published if published and os.path.exists(published) else local


def ensure_files(root):
    """Create the missing memory files from the templates; returns the created paths."""
    os.makedirs(learn_dir(root), exist_ok=True)
    created = []
    for name, template in TEMPLATES.items():
        path = glossary_path(root) if name == "GLOSSARY.md" else os.path.join(learn_dir(root), name)
        if not os.path.exists(path):
            write_text(path, template.format(date=today()))
            created.append(path)
    return created


def read_or_empty(path):
    return read_text(path) if os.path.exists(path) else ""


# ------------------------------------------------------------------ parsing
def inbox_items(root):
    """[(done, text)] of INBOX.md lines."""
    text = read_or_empty(os.path.join(learn_dir(root), "INBOX.md"))
    return [(m.group(1) != " ", m.group(2).strip()) for m in re.finditer(r"^- \[( |x|X)\] (.+)$", text, re.M)]


def lessons(root):
    """[{id, status, scope, when, rule, why, line}] from LESSONS.md."""
    text = read_or_empty(os.path.join(learn_dir(root), "LESSONS.md"))
    out = []
    lines = text.splitlines()
    for no, line in enumerate(lines, 1):
        m = re.match(r"^##\s+(L-\d+)\s*·\s*([\w-]+)\s*·\s*(.+?)\s*$", line)
        if m:
            out.append({"id": m.group(1), "status": m.group(2).lower(), "scope": m.group(3), "line": no,
                        "when": "", "rule": "", "why": ""})
            continue
        f = re.match(r"^-\s*(Когда|When|Правило|Rule|Почему|Why)\s*:\s*(.*)$", line)
        if f and out:
            key = {"когда": "when", "when": "when", "правило": "rule", "rule": "rule"}.get(f.group(1).lower(), "why")
            out[-1][key] = f.group(2).strip()
    return out


def profile_items(root):
    """[(section, text)] of the bullets of PROFILE.md."""
    section, out = "", []
    for line in read_or_empty(os.path.join(learn_dir(root), "PROFILE.md")).splitlines():
        if line.startswith("## "):
            section = line[3:].strip()
        elif section and re.match(r"^-\s+\S", line):
            out.append((section, line[1:].strip()))
    return out


def glossary_terms(root):
    """[(term, meaning, where)] of the GLOSSARY.md table."""
    out = []
    for line in read_or_empty(glossary_path(root)).splitlines():
        if not line.startswith("|") or re.match(r"^\|[\s|:-]+\|$", line):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if cells and cells[0] not in ("מונח", "Term", "Термин") and cells[0]:
            out.append((cells[0], cells[1] if len(cells) > 1 else "", cells[2] if len(cells) > 2 else ""))
    return out


def frontmatter(path):
    m = re.match(r"---\r?\n(.*?)\r?\n---", read_or_empty(path), re.S)
    fields = {}
    for line in (m.group(1).splitlines() if m else []):
        key, sep, value = line.partition(":")
        if sep and re.match(r"^[A-Za-z-]+$", key.strip()):
            fields[key.strip()] = value.strip().strip("\"'")
    return fields


def project_skills(root):
    """[(name, description, path)] of the skills the kit made for this project (.claude/skills/tlp-*)."""
    out = []
    for path in sorted(glob.glob(os.path.join(root, ".claude", "skills", "tlp-*", "SKILL.md"))):
        fm = frontmatter(path)
        out.append((os.path.basename(os.path.dirname(path)), fm.get("description", ""), path))
    return out


def sensitive(text):
    """Why `text` must not be stored, or None."""
    if SECRET_RE.search(text):
        return "looks like a secret or a connection string"
    if EMAIL_RE.search(text):
        return "contains an e-mail address"
    if DIGITS_RE.search(text) or PHONE_RE.search(text):
        return "contains a long number (id, account, phone)"
    return None


def norm(text):
    return re.sub(r"\W+", " ", text.lower()).strip()


def short(text, limit=200):
    text = re.sub(r"\s+", " ", text).strip()
    return text if len(text) <= limit else text[:limit - 1] + "…"


# ------------------------------------------------------------------ note
def append_inbox(root, entries):
    """entries: [(kind, scope, text, source)] → number written (duplicates of any line are skipped)."""
    ensure_files(root)
    path = os.path.join(learn_dir(root), "INBOX.md")
    old = read_text(path)
    # a line is "date · kind · scope · text · source": compare the text only
    known = {norm(" · ".join(t.split(" · ")[3:-1]) or t) for _, t in inbox_items(root)}
    lines = []
    for kind, scope, text, source in entries:
        text = short(text.replace("·", "-"), 220)
        if norm(text) in known:
            continue
        known.add(norm(text))
        lines.append(f"- [ ] {today()} · {kind} · {scope} · {text} · {source}")
    if lines:
        write_text(path, old.rstrip("\r\n") + "\n" + "\n".join(lines) + "\n", like=old)
    return len(lines)


def inbox_hint(root):
    new = sum(1 for done, _ in inbox_items(root) if not done)
    hint = f" — предложи пользователю /tl-retro" if new >= INBOX_HINT else ""
    return f"INBOX: {new} новых наблюдений{hint}"


def cmd_note(args):
    root = args.root
    text = " ".join(args.text).strip()
    if args.kind not in KINDS:
        print(f"ERROR: unknown kind '{args.kind}' (known: {', '.join(KINDS)})", file=sys.stderr)
        return 2
    if not SCOPE_RE.match(args.scope):
        print(f"ERROR: bad scope '{args.scope}' (kit, project, route:/tl-x, skill:NAME, agent:NAME, area:TOPIC)",
              file=sys.stderr)
        return 2
    if not text:
        print("ERROR: empty observation", file=sys.stderr)
        return 2
    why = sensitive(text)
    if why:
        print(f"ERROR: not written — {why}. Describe it without the value.", file=sys.stderr)
        return 2
    written = append_inbox(root, [(args.kind, args.scope, text, args.source)])
    print(("noted" if written else "already noted") + " · " + inbox_hint(root))
    return 0


