def default_home():
    env = os.environ.get("CLAUDE_CONFIG_DIR")
    return env if env else os.path.join(os.path.expanduser("~"), ".claude")


def transcript_dirs(home, root):
    """Claude Code keeps a project's transcripts in <home>/projects/<path with every other char as '-'>."""
    base = os.path.join(home, "projects")
    if not os.path.isdir(base):
        return []
    name = re.sub(r"[^A-Za-z0-9]", "-", os.path.abspath(root))
    exact = os.path.join(base, name)
    if os.path.isdir(exact):
        return [exact]
    want = os.path.normcase(os.path.abspath(root))
    found = []
    for folder in sorted(glob.glob(os.path.join(base, "*"))):  # long paths may be shortened: match by cwd
        for path in sorted(glob.glob(os.path.join(folder, "*.jsonl")))[:1]:
            try:
                with open(path, encoding="utf-8", errors="replace") as f:
                    for _, line in zip(range(30), f):
                        cwd = json.loads(line).get("cwd") if line.strip().startswith("{") else None
                        if cwd and os.path.normcase(os.path.abspath(cwd)) == want:
                            found.append(folder)
                            break
            except (OSError, ValueError):
                continue
    return found


def message_texts(content):
    """(plain texts, tool_result texts) of a transcript message content."""
    if isinstance(content, str):
        return [content], []
    texts, results = [], []
    for part in content if isinstance(content, list) else []:
        if not isinstance(part, dict):
            continue
        if part.get("type") == "text":
            texts.append(str(part.get("text", "")))
        elif part.get("type") == "tool_result":
            inner = part.get("content")
            if isinstance(inner, list):
                results += [str(p.get("text", "")) for p in inner if isinstance(p, dict)]
            elif inner is not None:
                results.append(str(inner))
    return texts, results


def classify(text):
    if STYLE_RE.search(text):
        return "style"
    if REMEMBER_RE.search(text):
        return "habit"
    if CORRECTION_RE.search(text):
        return "correction"
    return None


def harvest_transcripts(root, home, since):
    """[(kind, scope, text, source)] from this project's Claude Code transcripts; tolerant of format changes."""
    found = []
    for folder in transcript_dirs(home, root):
        for path in sorted(glob.glob(os.path.join(folder, "*.jsonl"))):
            if datetime.datetime.fromtimestamp(os.path.getmtime(path)) < since:
                continue
            after_interrupt = False
            try:
                f = open(path, encoding="utf-8", errors="replace")
            except OSError:
                continue
            with f:
                for line in f:
                    try:
                        item = json.loads(line)
                    except ValueError:
                        continue
                    if not isinstance(item, dict) or item.get("type") != "user" or item.get("isMeta"):
                        continue
                    origin = item.get("origin")
                    if isinstance(origin, dict) and origin.get("kind") not in (None, "human"):
                        continue
                    texts, results = message_texts((item.get("message") or {}).get("content"))
                    for res in results:
                        low = res.lower()
                        if low.lstrip().startswith(REJECTED_START) and REJECTED_MARK in low:
                            said = res[low.index(REJECTED_MARK) + len(REJECTED_MARK):].strip()
                            if said:
                                found.append(("correction", "project", "отклонил действие: " + said, "harvest:transcript"))
                    for text in texts:
                        if INTERRUPT_MARK in text:
                            after_interrupt = True
                            continue
                        stripped = text.strip()
                        if not stripped or stripped.startswith("<") or len(stripped) > 1500:
                            continue  # commands, system notes, pasted documents
                        kind = classify(stripped)
                        if after_interrupt:
                            found.append((kind or "correction", "project", "после прерывания: " + stripped,
                                          "harvest:transcript"))
                        elif kind:
                            found.append((kind, "project", stripped, "harvest:transcript"))
                        after_interrupt = False
    return found


def harvest_auto_memory(root, home):
    """Notes Claude Code's own auto memory already wrote for this project (before /tl-init turned it off)."""
    found = []
    for folder in transcript_dirs(home, root):
        for path in sorted(glob.glob(os.path.join(folder, "memory", "*.md"))):
            for line in read_or_empty(path).splitlines():
                m = re.match(r"^\s*[-*]\s+(.+)$", line)
                if m:
                    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", m.group(1)).strip()
                    found.append(("habit", "project", "auto memory: " + text, "harvest:auto-memory"))
    return found


def harvest_sql(root, since):
    path = os.path.join(memory_dir(root), "sql-journal.csv")
    if not os.path.exists(path):
        return []
    groups = {}
    with open(path, encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            status = (row.get("status") or "").strip()
            if not status or status == "ok":
                continue
            try:
                when = datetime.datetime.strptime(row.get("time", ""), "%Y%m%d-%H%M%S")
            except ValueError:
                when = since
            if when < since:
                continue
            key = (row.get("source", ""), row.get("env", ""), os.path.basename(row.get("file", "")), status.split()[0])
            groups[key] = groups.get(key, 0) + 1
    return [("mistake", "route:/tl-sql", f"SQL {status} ×{n}: {name} на {source} ({env})", "harvest:sql-journal")
            for (source, env, name, status), n in sorted(groups.items())]


def harvest_answers(root):
    """The same answer to the same question in two or more task folders → a habit worth a default."""
    seen = {}
    for path in glob.glob(os.path.join(memory_dir(root), "spec", "**", "*.md"), recursive=True):
        for q, a in QA_RE.findall(read_or_empty(path)):
            a = re.sub(r"\s*\(הוחל[^)]*\)\s*$", "", a)
            seen.setdefault(norm(q), {}).setdefault(norm(a), set()).add(os.path.dirname(path))
            seen[norm(q)].setdefault("_text", (q, a))
    out = []
    for key, answers in sorted(seen.items()):
        q, a = answers.pop("_text")
        for folders in answers.values():
            if len(folders) >= 2:
                out.append(("habit", "project", f"на вопрос «{short(q, 90)}» ответ всегда «{short(a, 60)}» "
                                                f"({len(folders)} задач)", "harvest:specs"))
    return out


def cmd_harvest(args):
    root = args.root
    since = datetime.datetime.now() - datetime.timedelta(days=args.days)
    home = args.home or default_home()
    candidates = (harvest_transcripts(root, home, since) + harvest_auto_memory(root, home)
                  + harvest_sql(root, since) + harvest_answers(root))
    safe, skipped = [], 0
    for kind, scope, text, source in candidates:
        if sensitive(text):
            skipped += 1
        else:
            safe.append((kind, scope, text, source))
    written = append_inbox(root, safe[:args.max])
    print(f"harvest: {written} new observation(s) from {len(candidates)} found "
          f"(last {args.days} days; transcripts: {len(transcript_dirs(home, root))} folder(s))"
          + (f"; {skipped} skipped — secrets or personal data" if skipped else ""))
    print(inbox_hint(root))
    return 0


