def build_active(root):
    """(text, warnings) of ACTIVE.md."""
    warnings = []
    prof = profile_items(root)
    active = [l for l in lessons(root) if l["status"] == "active"]
    terms = glossary_terms(root)
    skills = project_skills(root)
    out = list(ACTIVE_HEADER)
    if prof:
        out += ["", "## The user (style, habits, standing answers)"]
        out += [f"- {section}: {short(text, 180)}" for section, text in prof]
    if active:
        out += ["", "## Lessons (scope → when → rule)"]
        out += [f"- {l['id']} [{l['scope']}] {short(l['when'], 80)} → {short(l['rule'], 160)}" for l in active]
    if skills:
        out += ["", "## Project skills (made by /tl-retro; kit skills for this project)"]
        out += [f"- {name} — {short(desc, 150)}" for name, desc, _ in skills]
    new = sum(1 for done, _ in inbox_items(root) if not done)
    footer = [""] + ([f"Observations waiting: {new} → propose /tl-retro at the end of the reply."]
                     if new >= INBOX_HINT else [])
    if terms:
        room = max(MAX_ACTIVE_LINES - len(out) - len(footer) - 2, 1)  # 2 = blank line + heading
        shown = terms if len(terms) <= room else terms[:room - 1]     # keep a line for "… more"
        out += ["", "## Terms (the user's word = meaning · where)"]
        out += [f"- {t} = {short(m, 100)}" + (f" · {short(w, 60)}" if w else "") for t, m, w in shown]
        if len(shown) < len(terms):
            out.append(f"- … {len(terms) - len(shown)} more: {rel(root, glossary_path(root))}")
    if not (prof or active or terms or skills):
        out += ["", "Nothing learned yet."]
    out += footer
    if len(out) > MAX_ACTIVE_LINES:
        warnings.append(f"ACTIVE.md has {len(out)} lines (budget {MAX_ACTIVE_LINES}) — retire lessons or "
                        "shorten the profile in /tl-retro")
    return "\n".join(out).rstrip("\n") + "\n", warnings


def cmd_render(args):
    root = args.root
    for path in ensure_files(root):
        print(f"created {rel(root, path)}")
    text, warnings = build_active(root)
    path = os.path.join(learn_dir(root), "ACTIVE.md")
    old = read_or_empty(path)
    if old.replace("\r\n", "\n") != text:
        write_text(path, text)
    print(f"{rel(root, path)}: {len(text.splitlines())} lines")
    for w in warnings:
        print(f"WARN  {w}")
    return 0


# ------------------------------------------------------------------ lint
def lint(root):
    """[(level, file, line, message)]."""
    issues = []
    mem = learn_dir(root)
    if not os.path.isdir(mem):
        return issues

    def add(level, path, line, msg):
        issues.append((level, rel(root, path), line, msg))

    for name in ("LESSONS.md", "PROFILE.md", "INBOX.md"):
        path = os.path.join(mem, name)
        if os.path.exists(path) and parse_meta(read_text(path)) is None:
            add("ERROR", path, 1, "no tl-meta line")
    gpath = glossary_path(root)
    if os.path.exists(gpath) and parse_meta(read_text(gpath)) is None:
        add("ERROR", gpath, 1, "no tl-meta line")

    lpath = os.path.join(mem, "LESSONS.md")
    seen_ids, seen_rules = set(), {}
    items = lessons(root)
    for l in items:
        if l["id"] in seen_ids:
            add("ERROR", lpath, l["line"], f"{l['id']} is used twice")
        seen_ids.add(l["id"])
        if l["status"] not in STATUSES:
            add("ERROR", lpath, l["line"], f"{l['id']}: status '{l['status']}' (known: {', '.join(STATUSES)})")
        if not SCOPE_RE.match(l["scope"]):
            add("ERROR", lpath, l["line"], f"{l['id']}: bad scope '{l['scope']}'")
        body = " ".join((l["when"], l["rule"], l["why"]))
        why = sensitive(body)
        if why:
            add("ERROR", lpath, l["line"], f"{l['id']}: {why}")
        if l["status"] != "active":
            continue
        if not l["when"] or not l["rule"]:
            add("ERROR", lpath, l["line"], f"{l['id']}: an active lesson needs 'Когда:' and 'Правило:'")
        negated = NEGATION_RE.search(l["rule"])
        if WEAKEN_RE.search(l["rule"]) or (RISKY_RE.search(l["rule"]) and not negated):
            add("ERROR", lpath, l["line"], f"{l['id']}: the rule weakens CORE (tests, approval, commits, PROD) — "
                "a lesson may only add or narrow a rule")
        elif (RISKY_RE.search(l["rule"]) or CORE_TOPIC_RE.search(l["rule"])) and not negated:
            add("WARN", lpath, l["line"], f"{l['id']}: touches a CORE rule — make sure it only narrows it")
        key = (l["scope"], norm(l["rule"]))
        if key in seen_rules:
            add("WARN", lpath, l["line"], f"{l['id']}: same rule as {seen_rules[key]}")
        seen_rules.setdefault(key, l["id"])
        for ref in re.findall(r"`([\w.-]+/[\w./-]+\.[A-Za-z0-9]+)`", body):
            if not os.path.exists(os.path.join(root, ref)):
                add("WARN", lpath, l["line"], f"{l['id']}: `{ref}` no longer exists — retire or update the lesson")
    active = [l for l in items if l["status"] == "active"]
    if len(active) > MAX_LESSONS:
        add("ERROR", lpath, 1, f"{len(active)} active lessons (budget {MAX_LESSONS}) — retire or merge some")

    ppath = os.path.join(mem, "PROFILE.md")
    prof = profile_items(root)
    if len(prof) > MAX_PROFILE:
        add("ERROR", ppath, 1, f"{len(prof)} profile items (budget {MAX_PROFILE}) — merge them")
    for section, text in prof:
        why = sensitive(text)
        if why:
            add("ERROR", ppath, 1, f"'{short(text, 40)}': {why}")

    terms = {}
    for term, meaning, where in glossary_terms(root):
        why = sensitive(" ".join((term, meaning, where)))
        if why:
            add("ERROR", gpath, 1, f"term '{term}': {why}")
        if norm(term) in terms:
            add("WARN", gpath, 1, f"term '{term}' is listed twice")
        terms[norm(term)] = meaning

    ipath = os.path.join(mem, "INBOX.md")
    inbox = inbox_items(root)
    for done, text in inbox:
        why = sensitive(text)
        if why:
            add("ERROR", ipath, 1, f"'{short(text, 40)}': {why} — delete the line")
    new = sum(1 for done, _ in inbox if not done)
    if new >= INBOX_TOO_MANY:
        add("WARN", ipath, 1, f"{new} observations wait — run /tl-retro")

    for name, desc, path in project_skills(root):
        fm = frontmatter(path)
        if fm.get("name") != name:
            add("ERROR", path, 1, f"project skill: name '{fm.get('name')}' differs from the folder '{name}'")
        if not desc:
            add("ERROR", path, 1, "project skill without a description — Claude cannot know when to use it")
        if parse_meta(read_text(path)) is None:
            add("WARN", path, 1, "project skill without a tl-meta line")
        why = sensitive(read_text(path))
        if why:
            add("ERROR", path, 1, f"project skill: {why}")

    apath = os.path.join(mem, "ACTIVE.md")
    text, warnings = build_active(root)
    for w in warnings:
        add("ERROR", apath, 1, w)
    if read_or_empty(apath).replace("\r\n", "\n") != text:
        add("WARN", apath, 1, "out of date — run tl_learn.py render")
    return issues


def cmd_lint(args):
    issues = lint(args.root)
    for level, path, line, msg in issues:
        print(f"{level:5} {path}:{line}  {msg}")
    errors = sum(1 for i in issues if i[0] == "ERROR")
    print(f"{errors} error(s), {len(issues) - errors} warning(s)")
    return 1 if errors else 0


